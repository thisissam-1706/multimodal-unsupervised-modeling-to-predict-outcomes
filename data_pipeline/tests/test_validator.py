# --------------------------------------------------------------- split / study_group taken from participants.tsv
def fake_dataset(tmp_path, folder, mutate=None):
    d = tmp_path / "data"
    d.mkdir()
    f = pd.read_csv(folder / "features.csv", dtype=str, keep_default_na=False, na_values=[""])
    p = f[["participant_id", "split", "study_group"]].rename(columns={"split": "recommended_split"})
    p["clinical_site"] = "UW"
    if mutate:
        mutate(p)
    p.to_csv(d / "participants.tsv", sep="\t", index=False)
    return d


def test_cross_check_passes_when_split_and_group_match_participants_tsv(tmp_path):
    f = make(tmp_path, name="v1", version="v1")
    d = fake_dataset(tmp_path, f)
    errs, notes = V.validate_report(f, data_dir=d)
    assert errs == [] and any("cross-checked" in n for n in notes)


def test_cross_check_catches_a_different_split(tmp_path):
    f = make(tmp_path, name="v1", version="v1")
    d = fake_dataset(tmp_path, f, lambda p: p.__setitem__("recommended_split", p["recommended_split"].where(p.index != 0, "test")
                                                           if p.loc[0, "recommended_split"] != "test" else "train"))
    assert has(V.validate(f, data_dir=d), "differs from recommended_split")


def test_cross_check_catches_a_different_group_and_unknown_ids(tmp_path):
    f = make(tmp_path, name="v1", version="v1")
    d = fake_dataset(tmp_path, f, lambda p: p.__setitem__("study_group", p["study_group"].where(p.index != 0, "healthy")
                                                           if p.loc[0, "study_group"] != "healthy" else "insulin_dependent"))
    assert has(V.validate(f, data_dir=d), "study_group that differs")
    (tmp_path / "data2").mkdir()
    pd.DataFrame({"participant_id": ["other"], "recommended_split": ["train"], "study_group": ["healthy"]}).to_csv(
        tmp_path / "data2" / "participants.tsv", sep="\t", index=False)
    assert has(V.validate(f, data_dir=tmp_path / "data2"), "not in participants.tsv")


