def make(tmp_path, name="mock", version=None):
    folder = tmp_path / name
    MM.main(folder, seed=0)
    if version:
        s = json.loads((folder / "feature_schema.json").read_text())
        s["version"] = version
        (folder / "feature_schema.json").write_text(json.dumps(s))
    return folder


def csv_edit(folder, fn):
    df = pd.read_csv(folder / "features.csv", dtype=str, keep_default_na=False, na_values=[""])
    out = fn(df)
    (out if out is not None else df).to_csv(folder / "features.csv", index=False, na_rep="")


def schema_edit(folder, fn):
    p = folder / "feature_schema.json"
    s = json.loads(p.read_text())
    fn(s)
    p.write_text(json.dumps(s))


def feat(s, name):
    return next(f for f in s["features"] if f["name"] == name)


def errors(folder, **kw):
    return V.validate(folder, **kw)


def has(errs, text):
    return any(text in e for e in errs)


